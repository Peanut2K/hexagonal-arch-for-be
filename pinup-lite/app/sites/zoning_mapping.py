def normalize_zoning_code(raw_code: str) -> str:
    if not raw_code:
        return ""
    # Convert Thai numbers to Arabic
    norm = str(raw_code).translate(THAI_TO_ARABIC).strip()
    # Extract pattern like 'ย.7' from 'ย.7-25'
    m = re.match(r"([ก-ฮa-zA-Z]+\.?[0-9]+)", norm)
    if m:
        return m.group(1)
    return norm


def get_zoning_info(raw_code: str) -> dict:
    code_key = normalize_zoning_code(raw_code)
    rule = BKK_ZONING_MAP.get(
        code_key,
        {
            "name": "ไม่ระบุประเภท",
            "far": 0.0,
            "osr": 0.0,
        },
    )
    return {
        "zoning_code_key": code_key,
        "name": rule["name"],
        "far": rule["far"],
        "osr": rule["osr"],
    }
