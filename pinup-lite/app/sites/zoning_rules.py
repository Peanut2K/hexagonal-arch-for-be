def get_main_zoning_regulations(code_key: str) -> list:
    """Returns list of allowed land use activities and their condition texts for a zone code (e.g. 'ย.7')."""
    results = []
    if not code_key:
        return results

    clean_code = normalize_zoning_code(code_key)

    for item in MAIN_ZONING_MATRIX:
        zones_map = item["zones"]
        val = zones_map.get(clean_code)

        if val is None:
            val = zones_map.get(code_key, "")

        if val and val.lower() != "x":
            cond_text = CONDITION_TEXTS.get(val, "อนุญาตปกติ")
            results.append({
                "category": item.get("category", "ทั่วไป"),
                "activity": item["activity"],
                "condition": cond_text,
                "note": None
            })

    return results
